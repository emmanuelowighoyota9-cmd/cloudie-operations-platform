// Bundles the Hono API into a single ESM file that Vercel can deploy as one
// Node function: `api/index.js`.
//
// Why a build step instead of letting Vercel compile the TypeScript itself:
// @vercel/node transpiles each file under `api/` with an in-memory program built
// from the nearest tsconfig, but it discards that config's `files` and `include`
// lists. This repository's root tsconfig is solution-style (`"files": []` with
// `references` to the app/node projects), so the program contains no root files
// and the build fails with `api/index.ts: Emit skipped`. A pre-bundled entry has
// no imports left to trace, so nothing can go wrong at deploy time.
//
// Run from `npm run build`, after `tsc -b && vite build`.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outfile = join(root, "api", "index.js");

await build({
  entryPoints: [join(root, "backend", "src", "vercel-entry.ts")],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  logLevel: "info",
  banner: {
    js: "// GENERATED by scripts/build-vercel-api.mjs from backend/src/vercel-entry.ts.\n// Do not edit by hand — run `npm run build` instead.",
  },
  // Only our own source is bundled. npm packages stay real imports so the
  // function's file tracing sees them and picks up platform bindings such as
  // `@libsql/linux-x64-gnu`, which cannot be inlined into a bundle.
  packages: "external",
});

console.log(`[vercel-api] wrote ${relative(root, outfile)}`);
